package aula16;

public class Painel {

    public void exibir(String texto) {
        System.out.println("Exibindo Texto: " + texto);
    }

    public void exibir(int numero) {
        System.out.println("Exibindo Inteiro: " + numero);
    }

    public void exibir(boolean flag) {
        System.out.println("Exibindo Booleano: " + flag);
    }

    public void exibir(double decimal) {
        System.out.println("Exibindo Decimal: " + decimal);
    }
}