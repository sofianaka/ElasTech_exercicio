package estruturaDecisao;

public class atividade2 {
    public static void main(String[] args) {
        for(int i =1; i<=30; i++){
            System.out.println(i);
        }

        for(int i =10; i>=1; i--){
            System.out.println(i);
        }
        System.out.println("Fim");

        int numero = 1;
        while (numero <= 30) {
            System.out.println(numero);
            numero++;
        }

        int tabuada_2 = 2;

        for(int i =0; i<=10; i++){
            System.out.println(tabuada_2+ " x "+i+" = "+ tabuada_2*i );

        }

    }
    }
